"""Format writers for the raw files (xlsx, csv, pdf), byte-for-byte deterministic."""

from __future__ import annotations

import datetime as dt
import io
import re
import zipfile
from dataclasses import dataclass, field
from pathlib import Path

import pandas as pd
from openpyxl import Workbook
from openpyxl.styles import Alignment, Font
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from . import SYNTHETIC_MARKER

FIXED_TIME = dt.datetime(2026, 1, 1, 0, 0, 0)
ZIP_TIME = (2026, 1, 1, 0, 0, 0)


@dataclass
class Sheet:
    name: str
    title_rows: list[str]
    frame: pd.DataFrame
    group_header: list[tuple[str, int]] = field(default_factory=list)  # merged labels above the header
    text_columns: tuple[str, ...] = ()


def normalize_xlsx(path: Path) -> None:
    """Rewrite the zip with fixed entry timestamps and fixed document dates."""
    with zipfile.ZipFile(path) as z:
        entries = [(i.filename, z.read(i.filename)) for i in z.infolist()]
    buf = io.BytesIO()
    stamp = FIXED_TIME.strftime("%Y-%m-%dT%H:%M:%SZ").encode()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for name, data in entries:
            if name == "docProps/core.xml":
                data = re.sub(rb"(<dcterms:(?:created|modified)[^>]*>)[^<]*(<)", rb"\g<1>" + stamp + rb"\g<2>", data)
            info = zipfile.ZipInfo(name, date_time=ZIP_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o600 << 16
            z.writestr(info, data)
    path.write_bytes(buf.getvalue())


# Active raw layout (None = default). Set only by messy.write_raw for the duration of one write.
LAYOUT = None


def write_xlsx(path: Path, sheets: list[Sheet]) -> None:
    if LAYOUT is not None:
        sheets = [LAYOUT.sheet(path.name, s) for s in sheets]
    wb = Workbook()
    wb.remove(wb.active)
    wb.properties.title = SYNTHETIC_MARKER
    wb.properties.subject = "SYNTHETIC demo data generated by kaaran.synth"
    wb.properties.keywords = "SYNTHETIC"
    wb.properties.creator = "kaaran.synth"
    wb.properties.lastModifiedBy = "kaaran.synth"
    wb.properties.created = FIXED_TIME
    wb.properties.modified = FIXED_TIME
    for sheet in sheets:
        ws = wb.create_sheet(sheet.name)
        cols = list(sheet.frame.columns)
        width = len(cols)
        row = 1
        for line in sheet.title_rows:
            ws.cell(row, 1, line).font = Font(bold=row == 1)
            ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=width)
            row += 1
        if sheet.group_header:
            col = 1
            for label, span in sheet.group_header:
                ws.cell(row, col, label).alignment = Alignment(horizontal="center")
                if span > 1:
                    ws.merge_cells(start_row=row, start_column=col, end_row=row, end_column=col + span - 1)
                col += span
            row += 1
        for j, name in enumerate(cols, start=1):
            ws.cell(row, j, name).font = Font(bold=True)
        text_idx = [cols.index(c) + 1 for c in sheet.text_columns]
        for values in sheet.frame.itertuples(index=False):
            ws.append([None if pd.isna(v) else (v.item() if hasattr(v, "item") else v) for v in values])
        for j in text_idx:
            for (cell,) in ws.iter_rows(min_row=row + 1, min_col=j, max_col=j):
                cell.number_format = "@"
    wb.save(path)
    normalize_xlsx(path)


def write_csv(path: Path, title: str, frame: pd.DataFrame, encoding: str = "utf-8") -> None:
    if LAYOUT is not None:
        frame = LAYOUT.csv(path.name, frame)
    text = title + "\n" + frame.to_csv(index=False, lineterminator="\n")
    path.write_bytes(text.encode(encoding))


def write_pdf_tables(
    path: Path, title: str, sections: list[tuple[str, pd.DataFrame]], col_widths_mm: list[float]
) -> None:
    """Text-based PDF: a heading per section, tables whose header row repeats on every page."""
    styles = getSampleStyleSheet()
    heading = styles["Heading4"]
    footer_text = f"{SYNTHETIC_MARKER} | {title}"

    def on_page(canvas, doc):
        canvas.saveState()
        canvas.setFont("Helvetica-Bold", 8)
        canvas.drawString(15 * mm, A4[1] - 10 * mm, SYNTHETIC_MARKER)
        canvas.setFont("Helvetica", 7)
        canvas.drawString(15 * mm, 8 * mm, footer_text)
        canvas.drawRightString(A4[0] - 15 * mm, 8 * mm, f"Page {doc.page}")
        canvas.restoreState()

    doc = SimpleDocTemplate(
        str(path),
        pagesize=A4,
        leftMargin=15 * mm,
        rightMargin=15 * mm,
        topMargin=15 * mm,
        bottomMargin=14 * mm,
        title=f"{SYNTHETIC_MARKER} - {title}",
        author="kaaran.synth",
        subject="SYNTHETIC",
        creator="kaaran.synth",
        invariant=1,
    )
    style = TableStyle(
        [
            ("FONT", (0, 0), (-1, -1), "Helvetica", 7),
            ("FONT", (0, 0), (-1, 0), "Helvetica-Bold", 7),
            ("GRID", (0, 0), (-1, -1), 0.25, colors.grey),
            ("BACKGROUND", (0, 0), (-1, 0), colors.lightgrey),
            ("TOPPADDING", (0, 0), (-1, -1), 1),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 1),
        ]
    )
    story = []
    for text, frame in sections:
        story.append(Paragraph(text, heading))
        data = [list(frame.columns)] + frame.astype(str).values.tolist()
        story.append(Table(data, repeatRows=1, style=style, colWidths=[w * mm for w in col_widths_mm]))
        story.append(Spacer(1, 4 * mm))
    doc.build(story, onFirstPage=on_page, onLaterPages=on_page)
